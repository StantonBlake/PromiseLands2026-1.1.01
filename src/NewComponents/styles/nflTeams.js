const BADGE_BASE_URL =
  'https://r2.thesportsdb.com/images/media/team/badge';

const teamAliases = {
  JAC: 'JAX',
  WSH: 'WAS',
  LA: 'LAR',
  OAK: 'LV',
  SD: 'LAC',
  STL: 'LAR',
};

/**
 * Converts incoming team values into a supported abbreviation.
 */
export const normalizeTeamAbbreviation = (team) => {
  if (!team) {
    return '';
  }

  const normalizedTeam = String(team)
    .trim()
    .toUpperCase();

  return teamAliases[normalizedTeam] ?? normalizedTeam;
};

/**
 * Returns the complete NFL team object.
 */
export const getNFLTeam = (team) => {
  const abbreviation =
    normalizeTeamAbbreviation(team);

  return nflTeams[abbreviation] ?? null;
};

/**
 * Returns a complete team-logo URL.
 */
export const getTeamLogo = (team) => {
  const teamData = getNFLTeam(team);

  if (!teamData?.badgeToken) {
    return null;
  }

  return `${BADGE_BASE_URL}/${teamData.badgeToken}.png`;
};

/**
 * Returns a two-color team gradient.
 */
export const getTeamGradient = (team) => {
  const teamData = getNFLTeam(team);

  if (!teamData) {
    return `
      linear-gradient(
        135deg,
        #343a46 0%,
        #151922 100%
      )
    `;
  }

  return `
    linear-gradient(
      135deg,
      ${teamData.primary} 0%,
      ${teamData.secondary} 100%
    )
  `;
};

/**
 * Returns either dark or light text based on background brightness.
 */
export const getContrastColor = (
  hexColor = '#000000'
) => {
  if (typeof hexColor !== 'string') {
    return '#ffffff';
  }

  const cleanHex = hexColor
    .trim()
    .replace('#', '');

  const normalizedHex =
    cleanHex.length === 3
      ? cleanHex
          .split('')
          .map((character) => character.repeat(2))
          .join('')
      : cleanHex;

  if (!/^[0-9a-fA-F]{6}$/.test(normalizedHex)) {
    return '#ffffff';
  }

  const red = Number.parseInt(
    normalizedHex.slice(0, 2),
    16
  );

  const green = Number.parseInt(
    normalizedHex.slice(2, 4),
    16
  );

  const blue = Number.parseInt(
    normalizedHex.slice(4, 6),
    16
  );

  const luminance =
    (0.299 * red +
      0.587 * green +
      0.114 * blue) /
    255;

  return luminance > 0.58
    ? '#111111'
    : '#ffffff';
};

